"""Generate MIT demo geometry without any downloaded mesh, texture or customer CAD.

Run: blender --background --factory-startup --python tools/create_demo_assets.py
"""
from pathlib import Path
import json
import math
import bpy
from mathutils import Vector

ROOT = Path(__file__).resolve().parents[1]
ID = '0123456789abcdef0123456789abcdef'
OUT = ROOT / 'assets' / 'models' / ('user-' + ID)
OUT.mkdir(parents=True, exist_ok=True)
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete(use_global=False)


def material(name, color, metallic=0, roughness=.4):
    m = bpy.data.materials.new(name)
    m.diffuse_color = (*color, 1)
    m.use_nodes = True
    p = m.node_tree.nodes.get('Principled BSDF')
    p.inputs['Base Color'].default_value = (*color, 1)
    p.inputs['Metallic'].default_value = metallic
    p.inputs['Roughness'].default_value = roughness
    return m


top = material('Demo_Table_Top', (.12, .38, .32))
legs = material('Demo_Table_Legs', (.12, .14, .16), .65, .3)


def box(name, dimensions, center, mat, bevel):
    bpy.ops.mesh.primitive_cube_add(size=1, location=center)
    obj = bpy.context.object
    obj.name = name
    obj.dimensions = dimensions
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    obj.data.materials.append(mat)
    modifier = obj.modifiers.new('Soft edges', 'BEVEL')
    modifier.width = bevel
    modifier.segments = 3
    bpy.ops.object.modifier_apply(modifier=modifier.name)
    return obj


box('Side_Table_Top', (.8, .6, .05), (0, 0, .725), top, .012)
for x in [-.32, .32]:
    for y in [-.22, .22]:
        box('Side_Table_Leg', (.045, .045, .7), (x, y, .35), legs, .005)
bpy.context.scene.unit_settings.system = 'METRIC'
bpy.context.scene.unit_settings.scale_length = 1
bpy.ops.wm.save_as_mainfile(filepath=str(OUT / 'source.blend'))
bpy.ops.export_scene.gltf(filepath=str(OUT / 'model.glb'), export_format='GLB', export_yup=True)

# Thumbnail lighting and camera are not part of the saved native model.
bpy.ops.object.camera_add(location=(1.5, -1.9, 1.35))
camera = bpy.context.object
camera.rotation_euler = (Vector((0, 0, .4)) - camera.location).to_track_quat('-Z', 'Y').to_euler()
camera.data.type = 'ORTHO'
camera.data.ortho_scale = 1.35
scene = bpy.context.scene
scene.camera = camera
for location, power, size in [((1, -2, 3), 350, 3), ((-2, 1, 2), 200, 2)]:
    bpy.ops.object.light_add(type='AREA', location=location)
    light = bpy.context.object
    light.data.energy = power
    light.data.shape = 'DISK'
    light.data.size = size
    light.rotation_euler = (Vector((0, 0, .35)) - light.location).to_track_quat('-Z', 'Y').to_euler()
scene.render.engine = 'CYCLES'
scene.cycles.samples = 16
scene.render.resolution_x = scene.render.resolution_y = 256
scene.render.resolution_percentage = 100
scene.render.film_transparent = True
scene.render.filepath = str(OUT / 'preview.png')
bpy.ops.render.render(write_still=True)

item = dict(type='user_' + ID, folder='user-' + ID, name='示例边桌（MIT）', category='示例', width=.8, height=.75, depth=.6)
(ROOT / 'assets/models/catalog.json').write_text(json.dumps({'version': 1, 'items': [item]}, ensure_ascii=False, indent=2), encoding='utf8')
(OUT / 'LICENSE.txt').write_text('MIT. Generated by tools/create_demo_assets.py. No third-party mesh or texture.\nSee the project LICENSE.\n', encoding='utf8')

# Synthetic DXF: outer and inner wall edges, a divider and two room labels.
pairs = [(0, 'SECTION'), (2, 'HEADER'), (9, '$INSUNITS'), (70, 4), (0, 'ENDSEC'), (0, 'SECTION'), (2, 'ENTITIES')]


def line(x1, y1, x2, y2):
    pairs.extend([(0, 'LINE'), (8, 'WALL'), (10, x1), (20, y1), (30, 0), (11, x2), (21, y2), (31, 0)])


for x1, y1, x2, y2 in [(0, 0, 8000, 0), (8000, 0, 8000, 6000), (8000, 6000, 0, 6000), (0, 6000, 0, 0),
                         (200, 200, 7800, 200), (7800, 200, 7800, 5800), (7800, 5800, 200, 5800), (200, 5800, 200, 200),
                         (3900, 200, 3900, 5800), (4100, 200, 4100, 5800)]:
    line(x1, y1, x2, y2)
for name, x in [('Office A', 1800), ('Office B', 5600)]:
    pairs.extend([(0, 'TEXT'), (8, 'ROOM'), (10, x), (20, 3000), (30, 0), (40, 200), (1, name)])
pairs.extend([(0, 'ENDSEC'), (0, 'EOF')])
(ROOT / 'examples').mkdir(exist_ok=True)
(ROOT / 'examples/demo-office.dxf').write_text(''.join(str(k)+'\n'+str(v)+'\n' for k, v in pairs), encoding='ascii')
print('Generated public demo model and fictional CAD example.')
